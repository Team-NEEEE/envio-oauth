CREATE TABLE IF NOT EXISTS users (
    user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_github_id VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL,
    role VARCHAR(50) NOT NULL,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE
);

ALTER TABLE users ADD COLUMN IF NOT EXISTS user_github_id VARCHAR(255);
ALTER TABLE users ADD COLUMN IF NOT EXISTS user_id BIGINT GENERATED BY DEFAULT AS IDENTITY;
ALTER TABLE users ADD COLUMN IF NOT EXISTS email VARCHAR(255);
ALTER TABLE users ADD COLUMN IF NOT EXISTS role VARCHAR(50);

UPDATE users
SET user_github_id = CONCAT('legacy-', MD5(ctid::TEXT))
WHERE user_github_id IS NULL;

UPDATE users
SET email = CONCAT(user_github_id, '@users.noreply.github.com')
WHERE email IS NULL;

UPDATE users
SET role = 'VIEWER'
WHERE role IS NULL;

ALTER TABLE users ALTER COLUMN user_github_id SET NOT NULL;
ALTER TABLE users ALTER COLUMN email SET NOT NULL;
ALTER TABLE users ALTER COLUMN role SET DEFAULT 'VIEWER';
ALTER TABLE users ALTER COLUMN role SET NOT NULL;

CREATE UNIQUE INDEX IF NOT EXISTS uk_users_github_id
    ON users (user_github_id);

CREATE TABLE IF NOT EXISTS user_devices (
    user_device_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    device_name VARCHAR(255) NOT NULL,
    public_key TEXT NOT NULL,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE
);
